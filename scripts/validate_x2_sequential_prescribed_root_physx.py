def _linear_q(start: np.ndarray, goal: np.ndarray, count: int) -> list[np.ndarray]:
    count = max(int(count), 2)
    return [start + alpha * (goal - start) for alpha in np.linspace(0.0, 1.0, count)]


def _root_segment(start: np.ndarray, goal: np.ndarray, count: int = 2) -> list[np.ndarray]:
    """Deterministically interpolate two prescribed root-link poses.

    This is a waypoint constructor, not a trajectory optimizer.  It follows
    the *same* endpoint-exact convention as ``scheduled_root_motion``:
    translation is linear in world coordinates and rotation is interpolated
    on SO(3).  In particular, do not use ``se3_error`` as a Lie log here;
    that helper is an IK residual and its translational part does not produce
    an endpoint-exact transform when passed to ``se3_exp``.
    """

    start_pose = validate_transform(start, "root_segment.start")
    goal_pose = validate_transform(goal, "root_segment.goal")
    return [
        make_transform(
            start_pose[:3, :3] @ so3_exp(float(alpha) * so3_log(start_pose[:3, :3].T @ goal_pose[:3, :3])),
            (1.0 - float(alpha)) * start_pose[:3, 3] + float(alpha) * goal_pose[:3, 3],
        )
        for alpha in np.linspace(0.0, 1.0, max(int(count), 2))
    ]


def _required_q_steps(start: np.ndarray, goal: np.ndarray, *, dt: float, velocity_limit: Any) -> int:
    """Time-parameterize a staged target without optimizing a q trajectory."""

    if dt <= 0.0:
        raise ValueError("dt and velocity_limit must be positive")
    limits = np.asarray(velocity_limit, dtype=np.float64)
    if np.any(~np.isfinite(limits)) or np.any(limits <= 0.0):
        raise ValueError("dt and velocity_limit must be positive")
    deltas = np.abs(np.asarray(goal, dtype=np.float64) - np.asarray(start, dtype=np.float64))
    return max(2, int(math.ceil(float(np.max(deltas / (limits * dt))))) + 1)


def _trajectory_rows(binding: FR5Binding, q_rows: np.ndarray, H0: np.ndarray) -> list[np.ndarray]:
    # The X2 USD root is the wrist/hand root in world coordinates.  The FR5
    # binding already returns that wrist pose in the world frame; applying
    # H0^-1 here would move the simulated hand into an unrelated relative
    # frame and make the object-contact sensor miss the intended grasp.
    return [binding.hand_fk(q) for q in q_rows]


def _cartesian_twist_rows(
    binding: FR5Binding,
    H0: np.ndarray,
    root_start: np.ndarray,
    root_goal: np.ndarray,
    count: int,
    q_initial: np.ndarray,
) -> list[np.ndarray]:
    """Deterministic Cartesian transit with IK warm starts; no trajectory optimization."""

    start = validate_transform(root_start, "root_start")
    goal = validate_transform(root_goal, "root_goal")
    delta = transform_multiply(transform_inverse(start), goal)
    twist = se3_error(np.eye(4, dtype=np.float64), delta)
    rows: list[np.ndarray] = []
    q_seed = np.asarray(q_initial, dtype=np.float64).copy()
    for alpha in np.linspace(0.0, 1.0, max(int(count), 2)):
        target_root = transform_multiply(start, se3_exp(alpha * twist))
        result = solve_fr5_ik(binding, target_root, q_seed)
        if not result.converged:
            raise X2DualValidationError(
                f"cartesian transit IK failed at alpha={alpha:.6f}: {result.message}"
            )
        q_seed = result.q
        rows.append(transform_multiply(transform_inverse(H0), binding.hand_fk(result.q)))
    return rows


def _finite_state(*values: Any) -> bool:
    return all(bool(np.isfinite(np.asarray(value)).all()) for value in values)


def _load_table_support_config(
    *,
    o2_manifest: dict[str, Any],
    o2_manifest_path: Path,
    front_scene_pose_path: Path | None,
) -> dict[str, Any]:
    """Resolve the one physical table authorized by the O1/O2 scene poses.

    The O2 manifest is already evidence-validated by the manifest loader.
    This function only accepts the explicitly named layout and checks that O1
    names the same support.  It intentionally does not infer a table height
    from the grasp terminal pose.
    """

    if front_scene_pose_path is None:
        raise X2DualValidationError("--table-supported-scene requires --front-scene-pose")
    try:
        provenance = o2_manifest["pose_provenance"]
        support_id = str(provenance["support_id"])
        layout_path = Path(str(provenance["source_id"])).expanduser().resolve()
        layout = json.loads(layout_path.read_text(encoding="utf-8"))
        if layout.get("schema_version") != "x2_minimal_closure_scene_layout_v1":
            raise ValueError("layout schema_version must be x2_minimal_closure_scene_layout_v1")
        expected_back = Path(str(layout["back_scene_pose"])).expanduser().resolve()
        expected_front = Path(str(layout["front_scene_pose"])).expanduser().resolve()
        if expected_back != o2_manifest_path.expanduser().resolve():
            raise ValueError("layout back_scene_pose does not match --o2-scene-pose-manifest")
        if expected_front != front_scene_pose_path.expanduser().resolve():
            raise ValueError("layout front_scene_pose does not match --front-scene-pose")
        table_top_z_m = float(layout["table_top_z_m"])
        if not math.isfinite(table_top_z_m):
            raise ValueError("table_top_z_m must be finite")
        support_fixture = layout.get("support_fixture")
        if support_fixture is not None:
            if support_fixture.get("type") != "dual_square_pedestals":
                raise ValueError("unsupported support_fixture type")
            pedestal_height_m = float(support_fixture["height_m"])
            pedestal_size_xy_m = float(support_fixture["size_xy_m"])
            pedestal_top_z_m = float(support_fixture["top_z_m"])
            front_xy_m = [
                float(value) for value in support_fixture["front_xy_m"]
            ]
            back_xy_m = [
                float(value) for value in support_fixture["back_xy_m"]
            ]
            if (
                not math.isfinite(pedestal_height_m)
                or pedestal_height_m <= 0.0
                or not math.isfinite(pedestal_size_xy_m)
                or pedestal_size_xy_m <= 0.0
                or len(front_xy_m) != 2
                or len(back_xy_m) != 2
                or not np.isfinite(front_xy_m + back_xy_m).all()
                or not math.isclose(
                    pedestal_top_z_m,
                    table_top_z_m + pedestal_height_m,
                    abs_tol=1.0e-9,
                )
                or support_fixture.get("part_of_support_id")
                != "/World/Environment/Table"
            ):
                raise ValueError("invalid dual support pedestal geometry")
        front_payload = json.loads(expected_front.read_text(encoding="utf-8"))
        front_support_id = str(front_payload["pose_provenance"]["support_id"])
        if support_id != "/World/Environment/Table" or front_support_id != support_id:
            raise ValueError("O1 and O2 must both identify /World/Environment/Table")
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
        raise X2DualValidationError(
            f"invalid table support configuration from O1/O2 scene evidence: {error}"
        ) from error
    return {
        "support_id": support_id,
        "layout_path": str(layout_path),
        "table_top_z_m": table_top_z_m,
        "front_scene_pose": str(expected_front),
        "back_scene_pose": str(expected_back),
        "support_fixture": support_fixture,
    }


def _finger_name_from_runtime_body(body_name: str | None) -> str | None:
    if not isinstance(body_name, str):
        return None
    for finger_name, prefix in FINGER_PREFIX.items():
        if body_name.lower().startswith(f"rh_{prefix.lower()}"):
            return finger_name
    return None


def _classify_raw_contact_partner(raw_contact: dict[str, Any]) -> dict[str, Any]:
    """Attach a strict partner class to one raw PhysX contact patch."""

    record = dict(raw_contact)
    path = record.get("other_actor_path")
    # Isaac's raw API may return an ``Sdf.Path`` rather than a Python string.
    # Preserve its complete value in the artifact while keeping the evidence
    # record JSON serializable.
    if path is not None and not isinstance(path, str):
        path = str(path)
        record["other_actor_path"] = path
    body_name = record.get("other_link_name")
    path_text = path if isinstance(path, str) else ""
    if "/Environment/Table" in path_text:
        partner_kind = "table"
    elif "/Robot" in path_text:
        if body_name == "rh_palm":
            partner_kind = "rh_palm"
        elif _finger_name_from_runtime_body(body_name) is not None:
            partner_kind = "finger"
        else:
            partner_kind = "robot_other"
    elif "/ObjectRight" in path_text or "/ObjectLeft" in path_text:
        partner_kind = "object"
    else:
        partner_kind = "unresolved"
    record["partner_kind"] = partner_kind
    record["finger_name"] = _finger_name_from_runtime_body(body_name)
    return record


