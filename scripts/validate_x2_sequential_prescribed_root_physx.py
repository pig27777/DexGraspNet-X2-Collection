def _source_revalidated_contact_gradient_target(
    candidate: DualCandidate,
    *,
    branch_name: str,
    device: str,
) -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    """Reuse the archived validator's bounded contact-gradient close exactly.

    This is deliberately not a new relation model or local optimizer.  The
    source validator already defines a deterministic 1-mm surface-normal
    proposal and a descending, sampled bidirectional penetration line search.
    Here it supplies only one branch's immutable final micro-close target, after
    verifying that the archived valid record and raw record agree on the
    complete canonical actuator state.  The sequential worker deliberately
    retains its collision-free open-hand approach; replaying the closed raw q
    at a 4-cm task pregrasp was measured to eject O1 before acquisition.
    """

    if branch_name not in {"front", "back"}:
        raise X2DualValidationError("source revalidated close branch must be front or back")
    branch = candidate.front if branch_name == "front" else candidate.back
    object_label = "O1" if branch_name == "front" else "O2"
    source_valid_path = Path(branch.source_valid).expanduser().resolve()
    try:
        source_valid = json.loads(source_valid_path.read_text(encoding="utf-8"))
        source_raw_value = source_valid["validation"]["source_raw"]
    except (OSError, KeyError, TypeError, json.JSONDecodeError) as exc:
        raise X2DualValidationError(
            f"{branch_name} source valid record does not expose validation.source_raw: {source_valid_path}"
        ) from exc
    source_raw_path = Path(source_raw_value).expanduser().resolve()
    raw = load_raw_candidate(source_raw_path)
    raw_q = np.asarray(
        [raw.actuator_by_name[name] for name in EXPECTED_ACTUATOR_NAMES],
        dtype=np.float64,
    )
    archived_q = _external_q(load_source_actuator(source_valid_path))
    if not np.allclose(raw_q, archived_q, atol=1.0e-7, rtol=0.0):
        raise X2DualValidationError(
            f"{branch_name} source raw actuator state disagrees with its archived valid record"
        )

    # Keep the mature source implementation authoritative instead of copying
    # its surface/contact-gradient or line-search logic into this worker.
    from scripts.validate_x2_mesh_grasps_physx import _compute_contact_closing_targets

    source_args = SimpleNamespace(
        no_force_closing=False,
        closing_contact_threshold=0.003,
        closing_displacement=0.001,
        closing_gradient_scale=100.0,
        penetration_threshold=0.001,
        closing_penetration_cap=0.0015,
    )
    targets, closing_audit = _compute_contact_closing_targets(
        [raw], device=device, args=source_args
    )
    target = np.asarray(targets[0].detach().cpu(), dtype=np.float64)
    if target.shape != raw_q.shape or not np.isfinite(target).all():
        raise X2DualValidationError("source contact-gradient target is not finite 12D q")
    audit = dict(closing_audit["samples"][0])
    if not audit.get("selected_target_safe", False):
        raise X2DualValidationError("source contact-gradient target did not pass its static safety audit")
    return raw_q, target, {
        "mode": "archived_source_contact_gradient_line_search",
        "branch": branch_name,
        "object_role": object_label,
        "source_valid": str(source_valid_path),
        "source_raw": str(source_raw_path),
        "source_raw_matches_valid_actuator": True,
        "raw_q_external_order": raw_q.tolist(),
        "target_q_external_order": target.tolist(),
        "closing_audit": audit,
    }


def _apply_front_finger_close_scales(
    target_external: np.ndarray,
    reference_external: np.ndarray,
    candidate: DualCandidate,
    raw_specs: Any,
) -> tuple[np.ndarray, dict[str, Any]]:
    """Apply an explicit per-finger bounded delta-q to the O1 close target."""

    target = np.asarray(target_external, dtype=np.float64)
    reference = np.asarray(reference_external, dtype=np.float64)
    if target.shape != (len(EXPECTED_ACTUATOR_NAMES),) or reference.shape != target.shape:
        raise X2DualValidationError("front close finger scaling requires finite 12D external commands")
    if not np.isfinite(target).all() or not np.isfinite(reference).all():
        raise X2DualValidationError("front close finger scaling received non-finite commands")
    result = target.copy()
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    for raw in raw_specs or ():
        if not isinstance(raw, (list, tuple)) or len(raw) != 2:
            raise X2DualValidationError("--front-close-finger-scale requires FINGER SCALE")
        finger = str(raw[0]).strip().lower()
        if finger in seen:
            raise X2DualValidationError(f"duplicate front close finger scale: {finger}")
        seen.add(finger)
        if finger not in candidate.front.finger_names:
            raise X2DualValidationError(
                f"front close finger scale is not front-owned by this candidate: {finger}"
            )
        try:
            scale = float(raw[1])
        except (TypeError, ValueError) as exc:
            raise X2DualValidationError("front close finger scale must be numeric") from exc
        if not math.isfinite(scale) or scale < 0.0 or scale > 1.1:
            raise X2DualValidationError("front close finger scale must lie in [0,1.1]")
        prefix = f"rh_{FINGER_PREFIX[finger].lower()}"
        indices = [
            index
            for index, name in enumerate(EXPECTED_ACTUATOR_NAMES)
            if name.lower().startswith(prefix)
        ]
        if not indices:
            raise X2DualValidationError(
                f"front close finger scale resolved no actuator axes: {finger}"
            )
        original = result[indices].copy()
        result[indices] = reference[indices] + scale * (
            target[indices] - reference[indices]
        )
        rows.append(
            {
                "finger": finger,
                "scale": scale,
                "actuator_names": [EXPECTED_ACTUATOR_NAMES[index] for index in indices],
                "unscaled_target_rad": original.tolist(),
                "reference_rad": reference[indices].tolist(),
                "applied_target_rad": result[indices].tolist(),
            }
        )
    return result, {
        "enabled": bool(rows),
        "mode": "bounded_front_owned_finger_target_interpolation",
        "reference": "q_safe",
        "rows": rows,
    }


