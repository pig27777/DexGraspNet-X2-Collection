        def _interpolate_visual_arm(
            start: np.ndarray,
            goal: np.ndarray,
            step_index: int,
            step_count: int,
        ) -> np.ndarray:
            if step_count <= 1:
                return np.asarray(goal, dtype=np.float64).copy()
            alpha = float(step_index) / float(step_count - 1)
            return (1.0 - alpha) * np.asarray(start, dtype=np.float64) + alpha * np.asarray(goal, dtype=np.float64)

        def _resample_screened_visual_arm(
            source: np.ndarray,
            step_index: int,
            step_count: int,
        ) -> np.ndarray:
            values = np.asarray(source, dtype=np.float64)
            if values.ndim != 2 or values.shape[1] != 6 or len(values) == 0:
                raise X2DualValidationError("FR5 visual replay received an invalid screened q_arm segment")
            if len(values) == 1 or step_count <= 1:
                return values[-1].copy()
            coordinate = float(step_index) * float(len(values) - 1) / float(step_count - 1)
            lower = int(math.floor(coordinate))
            upper = min(lower + 1, len(values) - 1)
            alpha = coordinate - float(lower)
            return (1.0 - alpha) * values[lower] + alpha * values[upper]

