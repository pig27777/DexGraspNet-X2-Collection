def _pose(T: np.ndarray, origin: Any, *, device: str):
    import torch

    value = torch.zeros((1, 7), dtype=torch.float32, device=device)
    value[0, :3] = torch.as_tensor(np.asarray(origin[0].detach().cpu()), dtype=torch.float32, device=device)
    value[0, :3] += torch.as_tensor(T[:3, 3], dtype=torch.float32, device=device)
    value[0, 3:7] = torch.as_tensor(_matrix_to_quaternion_xyzw(T[:3, :3]), dtype=torch.float32, device=device)
    return value


def _matrix_to_quaternion_xyzw(matrix: Any) -> np.ndarray:
    """Convert a proper rotation to Isaac's ``[x, y, z, w]`` convention."""

    rotation = np.asarray(matrix, dtype=np.float64)
    if rotation.shape != (3, 3) or not np.isfinite(rotation).all():
        raise ValueError("rotation must be finite with shape (3, 3)")
    trace = float(np.trace(rotation))
    if trace > 0.0:
        scale = 2.0 * math.sqrt(trace + 1.0)
        return np.asarray(
            [
                (rotation[2, 1] - rotation[1, 2]) / scale,
                (rotation[0, 2] - rotation[2, 0]) / scale,
                (rotation[1, 0] - rotation[0, 1]) / scale,
                0.25 * scale,
            ],
            dtype=np.float64,
        )
    diagonal = np.diag(rotation)
    index = int(np.argmax(diagonal))
    if index == 0:
        scale = 2.0 * math.sqrt(max(1.0 + diagonal[0] - diagonal[1] - diagonal[2], 1.0e-12))
        return np.asarray(
            [0.25 * scale, (rotation[0, 1] + rotation[1, 0]) / scale, (rotation[0, 2] + rotation[2, 0]) / scale, (rotation[2, 1] - rotation[1, 2]) / scale],
            dtype=np.float64,
        )
    if index == 1:
        scale = 2.0 * math.sqrt(max(1.0 + diagonal[1] - diagonal[0] - diagonal[2], 1.0e-12))
        return np.asarray(
            [(rotation[0, 1] + rotation[1, 0]) / scale, 0.25 * scale, (rotation[1, 2] + rotation[2, 1]) / scale, (rotation[0, 2] - rotation[2, 0]) / scale],
            dtype=np.float64,
        )
    scale = 2.0 * math.sqrt(max(1.0 + diagonal[2] - diagonal[0] - diagonal[1], 1.0e-12))
    return np.asarray(
        [(rotation[0, 2] + rotation[2, 0]) / scale, (rotation[1, 2] + rotation[2, 1]) / scale, 0.25 * scale, (rotation[1, 0] - rotation[0, 1]) / scale],
        dtype=np.float64,
    )


def _quat_to_matrix_xyzw(quaternion: Any) -> np.ndarray:
    q = np.asarray(quaternion, dtype=np.float64)
    q = q / max(float(np.linalg.norm(q)), 1.0e-12)
    x, y, z, w = q
    return make_transform(
        np.array(
            [
                [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
            ],
            dtype=np.float64,
        ),
        np.zeros(3),
    )


def _root_matrix_from_data(root_pose: Any) -> np.ndarray:
    pose = np.asarray(root_pose.detach().cpu(), dtype=np.float64)
    result = _quat_to_matrix_xyzw(pose[3:7])
    result[:3, 3] = pose[:3]
    return result


def _external_q(q_canonical: np.ndarray) -> np.ndarray:
    by_name = dict(zip(X2_ACTUATOR_NAMES, np.asarray(q_canonical, dtype=np.float64)))
    return np.asarray([by_name[name] for name in EXPECTED_ACTUATOR_NAMES], dtype=np.float64)


def _retain_front_owned_axes(
    back_target_external: np.ndarray,
    front_hold_external: np.ndarray,
    candidate: DualCandidate,
) -> tuple[np.ndarray, tuple[str, ...]]:
    """Overlay the actually achieved O1 hold target onto later commands.

    The static dual candidate already holds the front-owned axes in its
    ``q_back_pre``/``q_back_close`` commands.  A source-revalidated O1 close,
    however, may safely add a small contact-gradient micro-close to precisely
    those axes.  Returning to their archived raw values while opening the
    opposite face is a real release command, not an innocuous preshape.

    Keep those front axes at the executed O1 target and retain the existing
    archived command on every back-owned axis.  This is role-gated command
    composition only: no learned relation, geometry modification, or new
    optimizer is introduced.
    """

    base = np.asarray(back_target_external, dtype=np.float64)
    hold = np.asarray(front_hold_external, dtype=np.float64)
    if base.shape != (len(EXPECTED_ACTUATOR_NAMES),) or hold.shape != base.shape:
        raise X2DualValidationError("front retention overlay requires two finite 12D external commands")
    if not np.isfinite(base).all() or not np.isfinite(hold).all():
        raise X2DualValidationError("front retention overlay received non-finite commands")
    prefixes = tuple(f"rh_{FINGER_PREFIX[finger]}" for finger in candidate.front.finger_names)
    result = base.copy()
    retained_names: list[str] = []
    for index, name in enumerate(EXPECTED_ACTUATOR_NAMES):
        if name.startswith(prefixes):
            result[index] = hold[index]
            retained_names.append(name)
    if not retained_names:
        raise X2DualValidationError("front retention overlay resolved no front-owned actuator axes")
    return result, tuple(retained_names)


